package servant.message;

public enum MessageType {
    SAY_HI_TO_BOOTSTRAP, BOOTSTRAP_SAYS_HELLO, JOINED_SYSTEM, LEFT_SYSTEM,

    SAY_HI_TO_SYSTEM_NODE, SYSTEM_NODE_SAYS_WELCOME, NEW_NODE_ARRIVAL, NODE_REMOVAL,

    IS_OK, OK, CHECK_SUSPECT, SUSPECT_RESULT, UPDATE_SYSTEM,

    ASK_FOR_TOKEN, TOKEN, TOKEN_QUERY, TOKEN_HAVE, TOKEN_REGENERATED,

    ADD_FILE, FILE_STORED, REQUEST_FILE, GIVE_FILE, REPLICATE_FILES, UPDATE_INDEX;

    public boolean isLogged() {
        return this != IS_OK && this != OK && this != UPDATE_SYSTEM;
    }
}
